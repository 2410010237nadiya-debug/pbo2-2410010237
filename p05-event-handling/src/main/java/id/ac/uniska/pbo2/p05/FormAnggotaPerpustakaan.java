    /** Mengosongkan semua isian dan mengembalikan fokus ke NPM. */
private void kosongkan() {
    npmField.setText("");
    namaField.setText("");
    prodiComboBox.setSelectedIndex(0);
    mahasiswaRadio.setSelected(true);
    emailField.setText("");
    hpField.setText("");
    alamatTextArea.setText("");
    setujuCheckBox.setSelected(false);
    npmInfoLabel.setText("0 dari 10 digit");
    npmField.requestFocusInWindow();
}

/** Menampilkan jumlah digit NPM yang sudah diketik. */
private void perbaruiJumlahDigit() {
    int jumlah = npmField.getText().trim().length();
    npmInfoLabel.setText(jumlah + " dari 10 digit");
}
