    private void perbaruiSaatMengetik(JTextField isian, JLabel pesan,
        java.util.function.Supplier<String> aturan) {
    isian.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
        private void cek() {
            if (!pesan.getText().isBlank()) {   // hanya jika sedang menampilkan kesalahan
                tandai(isian, pesan, aturan.get());
            }
        }
        @Override public void insertUpdate(javax.swing.event.DocumentEvent e) { cek(); }
        @Override public void removeUpdate(javax.swing.event.DocumentEvent e) { cek(); }
        @Override public void changedUpdate(javax.swing.event.DocumentEvent e) { cek(); }
    });
}
    
    private static class FilterAngka extends javax.swing.text.DocumentFilter {
    private final int maks;
    FilterAngka(int maks) { this.maks = maks; }

    @Override
    public void insertString(FilterBypass fb, int offset, String teks,
            javax.swing.text.AttributeSet attr) throws javax.swing.text.BadLocationException {
        replace(fb, offset, 0, teks, attr);
    }

    @Override
    public void replace(FilterBypass fb, int offset, int panjang, String teks,
            javax.swing.text.AttributeSet attr) throws javax.swing.text.BadLocationException {
        if (teks == null) {
            super.replace(fb, offset, panjang, teks, attr);
            return;
        }
        String angka = teks.replaceAll("\\D", "");
        int sisa = maks - (fb.getDocument().getLength() - panjang);
        if (sisa <= 0) {
            return;
        }
        if (angka.length() > sisa) {
            angka = angka.substring(0, sisa);
        }
        super.replace(fb, offset, panjang, angka, attr);
    }
}
    
