private void hitungRekap() {
    DefaultTableModel model = (DefaultTableModel) RekapTabel.getModel();
    int n = model.getRowCount();
    if (n == 0) {
        lblTotal.setText("  ");
        return;
    }
    double total = 0;
    for (int i = 0; i < n; i++) {
        total += Double.parseDouble(model.getValueAt(i, 5).toString());
    }
    lblTotal.setText(String.format(Locale.US,
            "Jumlah mahasiswa: %d, rata-rata nilai akhir: %.2f", n, total / n));
}
