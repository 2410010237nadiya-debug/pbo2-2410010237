    private void tambahMahasiswa(String npm, String nama, double tugas, double uts, double uas) {
    double akhir = 0.3 * tugas + 0.3 * uts + 0.4 * uas;
    DefaultTableModel model = (DefaultTableModel) RekapTabel.getModel();
    model.addRow(new Object[]{
        npm, nama,
        String.format(Locale.US, "%.0f", tugas),
        String.format(Locale.US, "%.0f", uts),
        String.format(Locale.US, "%.0f", uas),
        String.format(Locale.US, "%.2f", akhir),
        
    });
}

