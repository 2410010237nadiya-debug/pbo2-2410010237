    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed
    String npm = npmField.getText().trim();
    String nama = namaField.getText().trim();

    // validasi NPM
    if (!npm.matches("\\d{10}")) {
        tampilkanPesan("NPM harus 10 digit angka");
        npmField.requestFocus();
        return;
    }
    if (nama.isEmpty()) {
        tampilkanPesan("Nama tidak boleh kosong");
        namaField.requestFocus();
        return;
    }

    // validasi nilai 0-100
    double tugas, uts, uas;
    try {
        tugas = Double.parseDouble(tugasField.getText().trim());
        uts = Double.parseDouble(utsField.getText().trim());
        uas = Double.parseDouble(uasField.getText().trim());
    } catch (NumberFormatException e) {
        tampilkanPesan("Nilai harus berupa angka");
        return;
    }
    if (tugas < 0 || tugas > 100 || uts < 0 || uts > 100 || uas < 0 || uas > 100) {
        tampilkanPesan("Nilai harus 0 sampai 100");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) RekapTabel.getModel();

    // cegah NPM ganda
    for (int i = 0; i < model.getRowCount(); i++) {
        if (model.getValueAt(i, 0).toString().equals(npm)) {
            tampilkanPesan("NPM sudah ada di tabel");
            return;
        }
    }

    double akhir = 0.3 * tugas + 0.3 * uts + 0.4 * uas;
    String huruf;
    if (akhir >= 80) huruf = "A";
    else if (akhir >= 70) huruf = "B";
    else if (akhir >= 60) huruf = "C";
    else if (akhir >= 50) huruf = "D";
    else huruf = "E";

    model.addRow(new Object[]{
        npm, nama,
        String.format(Locale.US, "%.0f", tugas),
        String.format(Locale.US, "%.0f", uts),
        String.format(Locale.US, "%.0f", uas),
        String.format(Locale.US, "%.2f", akhir),
        huruf
    });

    hitungRekap();
    bersihkanForm();
    npmField.requestFocus();

 // TODO add your handling code here:
    }//GEN-LAST:event_simpanButtonActionPerformed

